"""Shared analysis for Theorem 2(b) and Theorem 3 (Haldane weight on the lattice).

analyse(m, S) takes a closed staggered history m[j, k, :] (site j, time slice k, periodic in
both directions; L even) and returns the plaquette charge Q of Eq. (11), the aliasing
remainder eps, and the residues of the three exact identities used in the proof:
    id1:  sum_jk Omega(z, n_j^k, n_j^{k+1}) = sum_j (-1)^j W_j          (mod 4 pi)
    id2:  sum_j (-1)^j W_j = 2 pi Q + eps/2                              (mod 4 pi)
    id3:  W_j - W_{j+1} = R_j                                            (mod 4 pi)
and the residue of the full statement, Eq. (12), as a phase:
    berry: | prod exp(-i S Omega(z,n,n')) - exp(-i 2 pi S Q) exp(-i S eps / 2) |.
Histories used in the manuscript are generated by `history(...)`.
"""
import numpy as np

from lmcore import Om, ZHAT, wrap


def analyse(m, S=0.5):
    L, n, _ = m.shape
    sgn = (-1.0) ** np.arange(L)
    nphys = m * sgn[:, None, None]
    W = lambda f: Om(ZHAT, f, np.roll(f, -1, axis=1)).sum(axis=1)
    Wphys, Wm = W(nphys), W(m)
    a, ap = m, np.roll(m, -1, axis=1)
    b = np.roll(m, -1, axis=0)
    bp = np.roll(b, -1, axis=1)
    Rj = (Om(a, ap, bp) + Om(a, bp, b)).sum(axis=1)
    Q = Rj.sum() / (4 * np.pi)
    X = (sgn * Wm).sum()
    eps = (sgn * Rj).sum()
    id1 = abs(wrap(Wphys.sum() - X))
    id2 = abs(wrap(X - (2 * np.pi * Q + eps / 2)))
    id3 = np.abs(wrap(Wm - np.roll(Wm, -1) - Rj)).max()
    berry = abs(np.exp(-1j * S * Wphys.sum()) - np.exp(-2j * np.pi * S * Q - 1j * S * eps / 2))
    # admissibility: all pairwise inner products in every plaquette triangle > -1/3
    tri = [(a, ap, bp), (a, bp, b)]
    mindot = min(min(np.einsum("...i,...i", x, y).min(), np.einsum("...i,...i", y, z).min(),
                     np.einsum("...i,...i", z, x).min()) for x, y, z in tri)
    return {"Q": Q, "Q_int_dev": abs(Q - round(Q)), "eps": eps, "id1": id1, "id2": id2,
            "id3": id3, "berry": berry, "admissible": bool(mindot > -1 / 3), "min_dot": mindot}


def trig_history(L, n, seed):
    """m = v/|v| with v a random trigonometric polynomial (|k| <= 2): analytic if min|v|>0.
    Seeds 0, 1, 2 are the three histories of Fig. 1(b)."""
    x = np.arange(L) / L
    t = np.arange(n) / n
    X, T = np.meshgrid(x, t, indexing="ij")
    v = np.zeros((L, n, 3))
    rng = np.random.default_rng(seed)
    for i in range(3):
        for kx in range(-2, 3):
            for kt in range(-2, 3):
                c = rng.normal() / (1 + kx * kx + kt * kt)
                ph = rng.uniform(0, 2 * np.pi)
                v[..., i] += c * np.cos(2 * np.pi * (kx * X + kt * T) + ph)
    return v / np.linalg.norm(v, axis=-1, keepdims=True), np.linalg.norm(v, axis=-1).min()


def chern_history(L, n, kx=1, m0=1.0, twist=0.7):
    """v = (sin 2pi kx x, sin 2pi t, m0 + cos 2pi kx x + cos 2pi t): degree +-kx for
    0<|m0|<2 and 0 for |m0|>2 (two-band Chern map); analytic since |v| > 0."""
    x = np.arange(L) / L
    t = np.arange(n) / n
    X, T = np.meshgrid(x, t, indexing="ij")
    v = np.stack([np.sin(2 * np.pi * kx * X), np.sin(2 * np.pi * T),
                  m0 + np.cos(2 * np.pi * kx * X) + np.cos(2 * np.pi * T)], -1)
    c, s = np.cos(twist), np.sin(twist)
    v = v @ np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]]).T      # avoid axis alignment
    return v / np.linalg.norm(v, axis=-1, keepdims=True), np.linalg.norm(v, axis=-1).min()


def finite_smooth_history(L, n, p=3):
    """A C^{p-1} (not C^p) history: the x-dependence contains |sin(pi x)|^p."""
    x = np.arange(L) / L
    t = np.arange(n) / n
    X, T = np.meshgrid(x, t, indexing="ij")
    v = np.stack([0.6 + np.abs(np.sin(np.pi * X)) ** p * np.cos(2 * np.pi * T),
                  0.4 * np.sin(2 * np.pi * (X + T)),
                  0.8 + 0.3 * np.cos(2 * np.pi * T)], -1)
    return v / np.linalg.norm(v, axis=-1, keepdims=True), np.linalg.norm(v, axis=-1).min()


if __name__ == "__main__":
    for seed in (0, 1, 2):
        m, vmin = trig_history(64, 64, seed)
        r = analyse(m)
        print(f"seed {seed}: Q={r['Q']:+.12f} eps={r['eps']:+.3e} berry-residue={r['berry']:.1e}"
              f" min|v|={vmin:.3f} admissible={r['admissible']}")
